"""Generate and verify the public literature workload inventory."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).parents[2]
REGISTRY = ROOT / "crates/asb-workloads/registry/v1/external-workloads.json"
JSON_OUT = ROOT / "docs/generated/workload-catalog-v1.json"
MD_OUT = ROOT / "docs/generated/WORKLOAD_CATALOG.md"
BUILTINS = [
    "original.bug-fix",
    "original.feature-addition",
    "original.refactoring",
    "original.test-generation",
    "original.dependency-migration",
    "original.build-repair",
    "original.repository-navigation",
]
ALIASES = {
    "swe-bench-lite": (
        "02e7a74ffd0b707aab73d203fe87bdc7c76afc8e",
        "MIT",
        "swebench.harness@02e7a74",
    ),
    "swe-bench-verified": (
        "02e7a74ffd0b707aab73d203fe87bdc7c76afc8e",
        "MIT",
        "swebench.harness@02e7a74",
    ),
    "humaneval-plus": (
        "e5d0ed0bab96280b60b637ec7f15b5e4841b0cb2",
        "MIT",
        "evalplus@v0.3.1-e5d0ed0b",
    ),
    "mbpp-plus": (
        "e5d0ed0bab96280b60b637ec7f15b5e4841b0cb2",
        "MIT",
        "evalplus@v0.3.1-e5d0ed0b",
    ),
}


def entry(record, *, ident=None, builtin=False):
    if builtin:
        return {
            "id": ident,
            "kind": "builtin",
            "source": "builtin",
            "source_revision": "asb-original-v1",
            "license": "MIT",
            "evaluator": "asb-original-oracle-v1",
            "adaptation": "none",
            "platform": "linux-x86_64:native-tested",
            "availability": "available",
            "evidence": "qualified",
        }
    revision = record["source"].get(
        "commit", record["source"].get("revision", record.get("version", "unknown"))
    )
    methodology = record.get("selection") == "methodology-only"
    return {
        "id": record["id"],
        "kind": "methodology" if methodology else "literature",
        "source": "literature",
        "source_revision": revision,
        "license": record["source"].get("license", "NOASSERTION"),
        "evaluator": record["evaluator"].get("entrypoint", "unqualified"),
        "adaptation": "fixture-only",
        "platform": record.get("platforms", {}).get("linux-x86_64", "unsupported"),
        "availability": "unavailable"
        if methodology or record["evaluator"]["provenance"].get("status") != "qualified"
        else "available",
        "evidence": record["evaluator"]["provenance"].get("status", "missing"),
    }


def inventory():
    data = json.loads(REGISTRY.read_text(encoding="utf-8"))
    records = [entry(None, ident=ident, builtin=True) for ident in BUILTINS]
    records.extend(entry(item) for item in data["workloads"])
    for ident, (revision, license, evaluator) in ALIASES.items():
        records.append(
            {
                "id": ident,
                "kind": "literature",
                "source": "literature",
                "source_revision": revision,
                "license": license,
                "evaluator": evaluator,
                "adaptation": "split-alias",
                "platform": "planned",
                "availability": "unavailable",
                "evidence": "planned",
            }
        )
    return {
        "schema_version": 1,
        "entries": sorted(records, key=lambda item: item["id"]),
    }


def markdown(document):
    lines = [
        "# Generated workload catalog",
        "",
        "This file is generated by `tools/quality/generate_workload_catalog.py`; edit the registry or workload contracts instead.",
        "",
        "| ID | Kind | Revision | Evaluator | Availability | Evidence |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    lines.extend(
        f"| `{item['id']}` | `{item['kind']}` | `{item['source_revision']}` | `{item['evaluator']}` | `{item['availability']}` | `{item['evidence']}` |"
        for item in document["entries"]
    )
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    document = inventory()
    expected_json = json.dumps(document, indent=2, sort_keys=False) + "\n"
    expected_md = markdown(document)
    if args.write:
        JSON_OUT.parent.mkdir(parents=True, exist_ok=True)
        JSON_OUT.write_text(expected_json, encoding="utf-8")
        MD_OUT.write_text(expected_md, encoding="utf-8")
        return 0
    if (
        JSON_OUT.read_text(encoding="utf-8") != expected_json
        or MD_OUT.read_text(encoding="utf-8") != expected_md
    ):
        raise SystemExit("generated workload catalog is stale; run with --write")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
